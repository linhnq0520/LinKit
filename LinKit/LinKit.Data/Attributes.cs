using System;

namespace LinKit.Data;

/// <summary>
/// Referential integrity action on foreign key deletion.
/// </summary>
public enum OnDeleteAction
{
    /// <summary>No action; the delete fails if referencing rows exist.</summary>
    NoAction,

    /// <summary>Deletes the referencing rows as well.</summary>
    Cascade,

    /// <summary>Sets the referencing column to <c>NULL</c>; the column must be nullable.</summary>
    SetNull,

    /// <summary>Blocks the delete while referencing rows exist.</summary>
    Restrict,
}

/// <summary>
/// Marks a class as a database table entity.
/// </summary>
[AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
public sealed class TableAttribute : Attribute
{
    /// <summary>Physical table name.</summary>
    public string Name { get; }

    /// <summary>Optional schema or owner the table belongs to.</summary>
    public string? Schema { get; set; }

    /// <summary>Optional documentation comment emitted alongside the schema.</summary>
    public string? Comment { get; set; }

    /// <summary>Maps the entity to a table.</summary>
    /// <param name="name">Physical table name.</param>
    public TableAttribute(string name)
    {
        Name = name;
    }
}

/// <summary>
/// Marks a property as the Primary Key of the table.
/// </summary>
[AttributeUsage(AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
public sealed class PrimaryKeyAttribute : Attribute
{
    /// <summary>Whether the database generates the key on insert.</summary>
    public bool AutoIncrement { get; set; } = false;

    /// <summary>Alias of <see cref="AutoIncrement"/>; a generated key is never written by the repository.</summary>
    public bool Generated
    {
        get => AutoIncrement;
        set => AutoIncrement = value;
    }

    /// <summary>Marks the property as the primary key, generated by the application.</summary>
    public PrimaryKeyAttribute() { }

    /// <summary>Marks the property as the primary key.</summary>
    /// <param name="autoIncrement">Whether the database generates the key on insert.</param>
    public PrimaryKeyAttribute(bool autoIncrement)
    {
        AutoIncrement = autoIncrement;
    }
}

/// <summary>
/// Customizes column mapping for a property.
/// </summary>
[AttributeUsage(AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
public sealed class ColumnAttribute : Attribute
{
    /// <summary>Physical column name; the property name is used when omitted.</summary>
    public string? Name { get; }

    /// <summary>Overrides the mapped database type for this column.</summary>
    public string? CustomSqlType { get; set; }

    /// <summary>Maximum length for string or binary columns; zero means provider default.</summary>
    public int Length { get; set; } = 0;

    /// <summary>Numeric precision; zero means provider default.</summary>
    public int Precision { get; set; } = 0;

    /// <summary>Numeric scale used together with <see cref="Precision"/>.</summary>
    public int Scale { get; set; } = 0;

    /// <summary>Whether the column accepts <c>NULL</c>.</summary>
    public bool IsNullable { get; set; } = true;

    /// <summary>Optional documentation comment emitted alongside the schema.</summary>
    public string? Comment { get; set; }

    /// <summary>
    /// Column position hint used when generating CREATE TABLE, INSERT and reader mapping.
    /// Default 0. Negative values go first, positive values go last (e.g. audit columns).
    /// Columns with equal Order keep base-class-first, declaration order. Only affects newly created tables.
    /// </summary>
    public int Order { get; set; } = 0;

    /// <summary>Maps the property to a column with the provider default settings.</summary>
    public ColumnAttribute() { }

    /// <summary>Maps the property to the named column.</summary>
    /// <param name="name">Physical column name.</param>
    public ColumnAttribute(string name)
    {
        Name = name;
    }
}

