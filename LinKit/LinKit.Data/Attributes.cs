/// <summary>
/// Marks the property that stores the tenant identifier, as a property-level alternative to <see cref="MultiTenantAttribute"/>.
/// </summary>
/// <remarks>
/// When a class declares no <see cref="MultiTenantAttribute"/>, this attribute supplies the tenant column, so the
/// property is scoped and guarded exactly as if <c>[MultiTenant]</c> had named it. An explicit <c>[MultiTenant]</c>
/// column name always wins. Declare only one tenant property per entity.
/// </remarks>
[AttributeUsage(AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
public sealed class TenantKeyAttribute : Attribute;

/// <summary>
/// Declares the column that stores the tenant identifier for an entity.
/// </summary>
/// <remarks>
/// When the declared column maps to a property, tenant scoping is automatic: reads and set-based writes gain
/// <c>WHERE tenant_column = @tenant</c>, and every write throws when <c>DataSession.TenantId</c> is not set or when the
/// entity carries a different tenant, so a row can never cross tenants. If no property maps to the column, no filter can
/// be emitted and the source generator reports <c>LNKDATA001</c>.
/// </remarks>
[AttributeUsage(AttributeTargets.Class, Inherited = true, AllowMultiple = false)]
public sealed class MultiTenantAttribute : Attribute
{
    /// <summary>Name of the column that stores the tenant identifier.</summary>
    public string TenantColumnName { get; }

    /// <summary>Declares the tenant column name for the entity.</summary>
    /// <param name="tenantColumnName">Tenant column name; defaults to <c>TenantId</c>. It must match a mapped property name or column name.</param>
    public MultiTenantAttribute(string tenantColumnName = "TenantId")
    {
        TenantColumnName = tenantColumnName;
    }
}
