/// <summary>
/// Serializes a complex object or collection into a JSON/JSONB column.
/// </summary>
/// <remarks>
/// Serialization stays Native AOT compatible when a <c>JsonSerializerContext</c> is supplied: either through
/// <see cref="JsonSerializerContextType"/> or globally through the context registered with
/// <c>UseJsonSerializerContext</c>. With neither in place the generated code falls back to the reflection-based
/// <c>JsonSerializer</c>, which is trimmed away in a Native AOT publish.
/// </remarks>
[AttributeUsage(AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
public sealed class JsonColumnAttribute : Attribute
{
    /// <summary>
    /// Optional custom <c>JsonSerializerContext</c> used for this property. When omitted, the context registered through
    /// <c>UseJsonSerializerContext</c> is used, and only then does the code fall back to reflection-based serialization.
    /// </summary>
    public Type? JsonSerializerContextType { get; }

    /// <summary>Maps the property to a JSON column, using the generated serializer context when one is available.</summary>
    public JsonColumnAttribute() { }

    /// <summary>Maps the property to a JSON column with an explicit serializer context.</summary>
    /// <param name="jsonSerializerContextType">Source-generated <c>JsonSerializerContext</c> used for AOT-safe serialization.</param>
    public JsonColumnAttribute(Type jsonSerializerContextType)
    {
        JsonSerializerContextType = jsonSerializerContextType;
    }
}

