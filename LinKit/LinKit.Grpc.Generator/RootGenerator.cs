using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace LinKit.Grpc.Generator;

[Generator]
public class RootGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var generatedNamespace = CreateGeneratedNamespace(context);
        var grpcClientServices = GrpcClientGeneratorPart.GetServices(context, generatedNamespace);
        var grpcServices = GrpcGeneratorPart.GetServices(context, generatedNamespace);

        GrpcClientGeneratorPart.Initialize(context, generatedNamespace);
        GrpcGeneratorPart.Initialize(context, generatedNamespace);

        var allServices = grpcClientServices
            .Combine(grpcServices)
            .Select(
                (combined, _) =>
                    new AllServicesInfo
                    {
                        GrpcClientServices = combined.Left,
                        GrpcServices = combined.Right,
                    }
            );

        context.RegisterSourceOutput(
            allServices.Combine(generatedNamespace),
            (spc, data) =>
            {
                var services = data.Left;
                var namespaceName = data.Right;
                // --- gRPC Client ---
                if (services.GrpcClientServices.Any())
                {
                    var src = GenerateClientDI(
                        services.GrpcClientServices.Select(s => s.RegistrationCode),
                        namespaceName
                    );
                    spc.AddSource(
                        "LinKit.Grpc.Client.DependencyInjection.g.cs",
                        SourceText.From(src, Encoding.UTF8)
                    );
                }

                // --- gRPC Server ---
                if (services.GrpcServices.Any())
                {
                    var src = GenerateServerDI(
                        services.GrpcServices.Select(s => s.RegistrationCode),
                        namespaceName
                    );
                    spc.AddSource(
                        "LinKit.Grpc.Server.DependencyInjection.g.cs",
                        SourceText.From(src, Encoding.UTF8)
                    );

                }
            }
        );
    }

    private static string GenerateClientDI(IEnumerable<string> registrations, string generatedNamespace)
    {
        var sb = new StringBuilder();
        sb.AppendLine(
            @"// <auto-generated/> by LinKit.Grpc.Generator
#nullable enable
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using LinKit.Grpc;
using LinKit.Core.Abstractions;
"
        );
        sb.AppendLine($"namespace {generatedNamespace}");
        sb.AppendLine("{");
        sb.AppendLine(
            @"    public static partial class ServicesExtensions
    {
        public static IServiceCollection AddLinKitGrpcClient(this IServiceCollection services)
        {
            // --- gRPC Client Mediator & Infrastructure ---
            services.TryAddSingleton<IGrpcInterceptorProvider, DefaultGrpcInterceptorProvider>();
            services.TryAddSingleton<IMetadataProvider, DefaultMetadataProvider>();
            services.TryAddSingleton<IGrpcClientFactory, DefaultGrpcClientFactory>();
"
        );

        foreach (var reg in registrations.Distinct())
        {
            sb.AppendLine($"            {reg}");
        }

        sb.AppendLine(
            @"            return services;
        }
    }
}"
        );
        return sb.ToString();
    }

    private static string GenerateServerDI(IEnumerable<string> registrations, string generatedNamespace)
    {
        var sb = new StringBuilder();
        sb.AppendLine(
            @"// <auto-generated/> by LinKit.Grpc.Generator
#nullable enable
using Microsoft.Extensions.DependencyInjection;
using LinKit.Grpc;
using LinKit.Core.Abstractions;
"
        );
        sb.AppendLine($"namespace {generatedNamespace}");
        sb.AppendLine("{");
        sb.AppendLine(
            @"    public static partial class ServicesExtensions
    {
        public static IServiceCollection AddLinKitGrpcServer(this IServiceCollection services)
        {
            // --- gRPC Server Services (Generated Implementations) ---"
        );

        foreach (var reg in registrations.Distinct())
        {
            sb.AppendLine($"            {reg}");
        }

        sb.AppendLine(
            @"            return services;
        }
    }
}"
        );
        return sb.ToString();
    }

    private static IncrementalValueProvider<string> CreateGeneratedNamespace(
        IncrementalGeneratorInitializationContext context)
    {
        var rootNamespace = context.AnalyzerConfigOptionsProvider.Select(
            static (provider, _) =>
                provider.GlobalOptions.TryGetValue("build_property.RootNamespace", out var value)
                    ? value
                    : string.Empty);
        var assemblyName = context.CompilationProvider.Select(
            static (compilation, _) => compilation.AssemblyName ?? string.Empty);

        return rootNamespace.Combine(assemblyName).Select(
            static (namespaces, _) =>
            {
                var root = string.IsNullOrWhiteSpace(namespaces.Left)
                    ? namespaces.Right
                    : namespaces.Left;
                return string.IsNullOrWhiteSpace(root) ? "Generated" : $"{root}.Generated";
            });
    }
}

internal record AllServicesInfo
{
    public IReadOnlyList<GrpcClientServiceInfo> GrpcClientServices { get; init; } =
        new List<GrpcClientServiceInfo>();
    public IReadOnlyList<GrpcServiceInfo> GrpcServices { get; init; } = new List<GrpcServiceInfo>();
}

internal record GrpcClientServiceInfo(string RegistrationCode);

internal record GrpcServiceInfo(string RegistrationCode);
