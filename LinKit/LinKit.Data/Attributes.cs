/// <summary>
/// Configures foreign key constraint linking to another table.
/// </summary>
[AttributeUsage(AttributeTargets.Property, Inherited = true, AllowMultiple = false)]
public sealed class ForeignKeyAttribute : Attribute
{
    /// <summary>Referenced table name.</summary>
    public string TargetTable { get; }

    /// <summary>Referenced column name; defaults to <c>Id</c>.</summary>
    public string TargetColumn { get; set; } = "Id";

    /// <summary>Action taken on the referencing rows when the target row is deleted.</summary>
    public OnDeleteAction OnDelete { get; set; } = OnDeleteAction.Cascade;

    /// <summary>Declares a foreign key to another table.</summary>
    /// <param name="targetTable">Referenced table name.</param>
    public ForeignKeyAttribute(string targetTable)
    {
        TargetTable = targetTable;
    }
}

