using System;
using System.Buffers;
using System.Diagnostics.CodeAnalysis;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.Json.Serialization.Metadata;

namespace LinKit.Core.Messaging;

/// <summary>
/// Central JSON contract for broker messages. Register your source-generated contexts once at startup
/// (<c>LinKitMessageJson.AddContext(MyJsonContext.Default)</c>) so serialization is reflection-free and Native AOT safe.
/// Types without a registered context fall back to reflection only when it is enabled; otherwise a clear error is thrown.
/// </summary>
public static class LinKitMessageJson
{
    private static readonly object Gate = new();
    private static volatile JsonSerializerOptions _options = Create(
        Array.Empty<IJsonTypeInfoResolver>()
    );
    private static IJsonTypeInfoResolver[] _resolvers = Array.Empty<IJsonTypeInfoResolver>();

    /// <summary>
    /// Gets the serializer options used for every broker message. The options are rebuilt whenever a context is added, so
    /// capture this property per call rather than caching the reference at startup.
    /// </summary>
    public static JsonSerializerOptions Options => _options;

    /// <summary>
    /// Adds a source-generated <see cref="JsonSerializerContext"/> to the resolver chain so its types serialize without
    /// reflection. Calling it twice with the same context has no effect, which makes it safe to call from several modules.
    /// </summary>
    /// <param name="context">The context generated by <c>System.Text.Json</c> for the application's message types.</param>
    public static void AddContext(JsonSerializerContext context)
    {
        ArgumentNullException.ThrowIfNull(context);
        lock (Gate)
        {
            if (Array.IndexOf(_resolvers, context) >= 0)
                return;
            var next = new IJsonTypeInfoResolver[_resolvers.Length + 1];
            _resolvers.CopyTo(next, 0);
            next[^1] = context;
            _resolvers = next;
            _options = Create(next);
        }
    }

    private static JsonSerializerOptions Create(IJsonTypeInfoResolver[] resolvers)
    {
        // Default (PascalCase) naming preserved for wire compatibility with messages produced before this contract existed.
        var options = new JsonSerializerOptions();
        foreach (var r in resolvers)
            options.TypeInfoResolverChain.Add(r);
        AddReflectionFallbackIfAvailable(options);
        return options;
    }

    // Reflection fallback is only wired up when the runtime actually allows it (never under Native AOT / trimming switches).
    [UnconditionalSuppressMessage(
        "Trimming",
        "IL2026",
        Justification = "Guarded by JsonSerializer.IsReflectionEnabledByDefault."
    )]
    [UnconditionalSuppressMessage(
        "AOT",
        "IL3050",
        Justification = "Guarded by RuntimeFeature.IsDynamicCodeSupported."
    )]
    private static void AddReflectionFallbackIfAvailable(JsonSerializerOptions options)
    {
        if (JsonSerializer.IsReflectionEnabledByDefault && RuntimeFeature.IsDynamicCodeSupported)
            options.TypeInfoResolverChain.Add(new DefaultJsonTypeInfoResolver());
    }

    /// <summary>
    /// Serializes a message to UTF-8 JSON.
    /// </summary>
    /// <param name="message">The message to serialize.</param>
    /// <returns>The UTF-8 encoded payload.</returns>
    /// <remarks>
    /// Payloads that are already JSON (<see cref="byte"/>, <see cref="ReadOnlyMemory{T}"/>, <see cref="string"/> and
    /// <see cref="JsonElement"/>) are passed through without re-serialization, which keeps the Outbox dispatch path free of
    /// redundant work.
    /// </remarks>
    /// <exception cref="ArgumentNullException"><paramref name="message"/> is <see langword="null"/>.</exception>
    /// <exception cref="NotSupportedException">
    /// The type has no registered context and reflection is disabled (Native AOT or trimming).
    /// </exception>
    public static byte[] SerializeToUtf8Bytes(object message)
    {
        ArgumentNullException.ThrowIfNull(message);

        // Payloads already in JSON form (e.g. from the Outbox or raw bytes/strings) need no type metadata.
        if (message is byte[] raw)
            return raw;
        if (message is ReadOnlyMemory<byte> memory)
            return memory.ToArray();
        if (message is string rawJson)
            return Encoding.UTF8.GetBytes(rawJson);
        if (message is JsonElement element)
        {
            var buffer = new ArrayBufferWriter<byte>();
            using (var writer = new Utf8JsonWriter(buffer))
                element.WriteTo(writer);
            return buffer.WrittenSpan.ToArray();
        }

        var info = _options.GetTypeInfo(message.GetType());
        return JsonSerializer.SerializeToUtf8Bytes(message, info);
    }

    /// <summary>
    /// Deserializes a UTF-8 JSON payload into <typeparamref name="T"/>.
    /// </summary>
    /// <typeparam name="T">Type to materialise.</typeparam>
    /// <param name="utf8Json">The raw payload received from the broker.</param>
    /// <returns>The deserialized value, or <see langword="default"/> when the payload holds the JSON literal
    /// <c>null</c>.</returns>
    /// <exception cref="JsonException">The payload is not valid JSON for <typeparamref name="T"/>.</exception>
    /// <exception cref="NotSupportedException">
    /// The type has no registered context and reflection is disabled (Native AOT or trimming).
    /// </exception>
    public static T? Deserialize<T>(ReadOnlySpan<byte> utf8Json)
    {
        var info = (JsonTypeInfo<T>)_options.GetTypeInfo(typeof(T));
        return JsonSerializer.Deserialize(utf8Json, info);
    }
}
